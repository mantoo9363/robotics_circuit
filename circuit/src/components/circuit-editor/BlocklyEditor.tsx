/* =========================================================
   GENERATORS
========================================================= */

function registerGenerators() {
  arduinoGenerator.forBlock["builtin_led"] = (block: Blockly.Block) => {
    const state = block.getFieldValue("STATE");
    return `digitalWrite(13, ${state});\n`;
  };
  arduinoGenerator.forBlock["set_pin"] = (
    block: Blockly.Block,
    generator: typeof arduinoGenerator,
  ) => {
    const pin =
      generator.valueToCode(block, "PIN", generator.ORDER_ATOMIC) || 0;
    const state =
      generator.valueToCode(block, "STATE", generator.ORDER_ATOMIC) || "LOW";
    return `\npinMode(${pin}, OUTPUT);\ndigitalWrite(${pin}, ${state});\n`;
  };
  arduinoGenerator.forBlock["analog_write"] = (
    block: Blockly.Block,
    generator: typeof arduinoGenerator,
  ) => {
    const pin =
      generator.valueToCode(block, "PIN", generator.ORDER_ATOMIC) || 0;
    const value =
      generator.valueToCode(block, "VALUE", generator.ORDER_ATOMIC) || 0;
    return `\nanalogWrite(${pin}, ${value});\n`;
  };
  arduinoGenerator.forBlock["serial_print"] = (
    block: Blockly.Block,
    generator: typeof arduinoGenerator,
  ) => {
    const text =
      generator.valueToCode(block, "TEXT", generator.ORDER_ATOMIC) || '""';
    return `\nSerial.println(${text});\n`;
  };
  arduinoGenerator.forBlock["delay_ms"] = (
    block: Blockly.Block,
    generator: typeof arduinoGenerator,
  ) => {
    const ms =
      generator.valueToCode(block, "MS", generator.ORDER_ATOMIC) || 0;
    return `\ndelay(${ms});\n`;
  };
}

