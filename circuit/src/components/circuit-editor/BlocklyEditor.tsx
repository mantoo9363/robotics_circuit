/* =========================================================
   WRAP ARDUINO CODE
========================================================= */

function wrapArduino(raw: string): string {
  const lines = raw.trim();
  if (!lines) return "// Drag blocks to generate code\n";
  return `// Generated by Blockly
  #include <Servo.h>

Servo servo;

void setup() {
  Serial.begin(9600);
  Serial.println("Blockly ready!");
}

void loop() {
${lines
  .split("\n")
  .map((l) => "  " + l)
  .join("\n")}
}
`;
}

/* =========================================================
   WRAP PYTHON CODE
========================================================= */

function wrapPython(raw: string, declaredPins: Set<number>): string {
  const lines = raw.trim();
  if (!lines) return "# Drag blocks to generate code\n";
  const declarations: string[] = [
    "# Generated by Blockly",
    "from machine import Pin, ADC, PWM",
    "import time",
    "",
  ];
  for (const pin of Array.from(declaredPins).sort((a, b) => a - b)) {
    declarations.push(`pin_${pin} = Pin(${pin}, Pin.OUT)`);
  }
  declarations.push("");
  declarations.push('print("Blockly ready!")');
  declarations.push("");
  declarations.push("while True:");
  const body = lines
    .split("\n")
    .map((l) => "    " + l)
    .join("\n");
  return [...declarations, body].join("\n") + "\n";
}

