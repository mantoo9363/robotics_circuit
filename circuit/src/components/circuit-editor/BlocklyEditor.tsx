    // Resize Blockly when container resizes
    const ro = new ResizeObserver(() => {
      if (workspaceRef.current) {
        Blockly.svgResize(workspaceRef.current);
      }
    });
    if (blocklyDiv.current) {
      ro.observe(blocklyDiv.current);
    }

    const savedWorkspaceXml = useBlocklyStore.getState().workspaceXml;
    let isRestoringWorkspace = false;

    if (savedWorkspaceXml) {
      try {
        isRestoringWorkspace = true;
        const xml = Blockly.utils.xml.textToDom(savedWorkspaceXml);
        Blockly.Xml.domToWorkspace(xml, workspaceRef.current);
      } catch (err) {
        console.warn("Blockly workspace restore error:", err);
      } finally {
        isRestoringWorkspace = false;
      }
    }

    // Initial fetch of variables
    if (workspaceRef.current) {
      const vars = workspaceRef.current.getAllVariables();
      setVariablesList(vars.map((v) => (v as any).name));
    }

