/* =========================================================
   GENERATORS
========================================================= */

function registerGenerators() {
  /* ---------------- BUILTIN LED ---------------- */

  arduinoGenerator.forBlock["builtin_led"] = (
    block: Blockly.Block
  ) => {
    const state = block.getFieldValue("STATE");

    return `digitalWrite(13, ${state});\n`;
  };

  /* ---------------- SET PIN ---------------- */

  arduinoGenerator.forBlock["set_pin"] = (
    block: Blockly.Block,
    generator: typeof arduinoGenerator
  )  => {
    const pin =
      generator.valueToCode(
        block,
        "PIN",
        generator.ORDER_ATOMIC
      ) || 0;

    const state =
      generator.valueToCode(
        block,
        "STATE",
        generator.ORDER_ATOMIC
      ) || "LOW";

    return `
pinMode(${pin}, OUTPUT);
digitalWrite(${pin}, ${state});
`;
  };

  /* ---------------- ANALOG WRITE ---------------- */

  arduinoGenerator.forBlock["analog_write"] = (
    block: Blockly.Block,
    generator: typeof arduinoGenerator
  )  => {
    const pin =
      generator.valueToCode(
        block,
        "PIN",
        generator.ORDER_ATOMIC
      ) || 0;

    const value =
      generator.valueToCode(
        block,
        "VALUE",
        generator.ORDER_ATOMIC
      ) || 0;

    return `
analogWrite(${pin}, ${value});
`;
  };

  /* ---------------- SERIAL PRINT ---------------- */

  arduinoGenerator.forBlock["serial_print"] = (
    block: Blockly.Block,
    generator: typeof arduinoGenerator
  ) => {
    const text =
      generator.valueToCode(
        block,
        "TEXT",
        generator.ORDER_ATOMIC
      ) || '""';

    return `
Serial.println(${text});
`;
  };

  /* ---------------- DELAY ---------------- */

  arduinoGenerator.forBlock["delay_ms"] = (
    block: Blockly.Block,
    generator: typeof arduinoGenerator
  ) => {
    const ms =
      generator.valueToCode(
        block,
        "MS",
        generator.ORDER_ATOMIC
      ) || 0;

    return `
delay(${ms});
`;
  };
}

