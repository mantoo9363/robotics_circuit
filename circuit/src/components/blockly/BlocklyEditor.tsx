/* =========================================================
   COMPONENT
========================================================= */

export default function BlocklyEditor() {
  const blocklyDiv =
    useRef<HTMLDivElement | null>(null);

  const workspaceRef =
    useRef<Blockly.WorkspaceSvg | null>(null);

  const [mounted, setMounted] =
    useState(false);

  useEffect(() => {
    setMounted(true);
  }, []);

  useEffect(() => {
    if (
      !mounted ||
      !blocklyDiv.current ||
      workspaceRef.current
    ) {
      return;
    }

    try {
      Blockly.defineBlocksWithJsonArray(
        CUSTOM_BLOCKS as any
      );
    } catch {}

    registerGenerators();

    workspaceRef.current = Blockly.inject(
      blocklyDiv.current,
      {
        toolbox: TOOLBOX,

        theme: Blockly.Theme.defineTheme(
          "arduinoLight",
          {
            name: "arduinoLight",

            base: Blockly.Themes.Classic,

            componentStyles: {
              workspaceBackgroundColour:
                "#f9f9f9",

              toolboxBackgroundColour:
                "#4C97FF",

              toolboxForegroundColour:
                "#fff",

              flyoutBackgroundColour:
                "#f1f5fb",

              flyoutForegroundColour:
                "#333",
            },
          }
        ),

        grid: {
          spacing: 20,
          length: 3,
          colour: "#ddd",
          snap: true,
        },

        zoom: {
          controls: true,
          wheel: true,
          startScale: 0.9,
        },

        trashcan: true,
      }
    );

    workspaceRef.current.addChangeListener(
      (event) => {
        if (
          event.type ===
            Blockly.Events.VIEWPORT_CHANGE ||
          event.type ===
            Blockly.Events.TOOLBOX_ITEM_SELECT ||
          event.type ===
            Blockly.Events.THEME_CHANGE
        ) {
          return;
        }

        if (!workspaceRef.current) {
          return;
        }

        try {
          const rawCode =
            arduinoGenerator.workspaceToCode(
              workspaceRef.current
            );

          const arduino =
            wrapArduino(rawCode);

          useBlocklyStore
            .getState()
            .setCode(arduino);

          useCircuitStore
            .getState()
            .setArduinoCode(arduino);

          console.log(arduino);
        } catch (err) {
          console.warn(
            "Blockly code gen error:",
            err
          );
        }
      }
    );

    return () => {
      try {
        if (workspaceRef.current) {
          workspaceRef.current.dispose();
        }

        workspaceRef.current = null;
      } catch (err) {
        console.error(err);
      }
    };
  }, [mounted]);

  if (!mounted) return null;

  return (
    <div className="w-full h-full flex flex-col">
      {/* STATUS BAR */}

      <div className="flex items-center gap-2 px-3 py-1 bg-[#4C97FF] text-[10px] text-white shrink-0">
        <span className="w-2 h-2 rounded-full bg-white animate-pulse" />

        <span>
          Blockly live sync active
        </span>

        <span className="ml-auto opacity-70">
          Drag blocks · press ▶ to simulate
        </span>
      </div>

      {/* BLOCKLY */}

      <div
        ref={blocklyDiv}
        className="flex-1 w-full"
      />

      {/* SERIAL MONITOR */}

      <div className="flex items-center gap-2 px-3 py-2 bg-white border-t border-gray-200 text-xs text-gray-500 shrink-0">
        📟 Serial Monitor
      </div>
    </div>
  );
}