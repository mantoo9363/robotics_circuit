/* =========================================================
   WRAP ARDUINO CODE
========================================================= */

function wrapArduino(raw: string): string {
  const lines = raw.trim();

  if (!lines) {
    return "// Drag blocks to generate code\n";
  }

  return `// Generated by Blockly

void setup() {
  Serial.begin(9600);
  Serial.println("Blockly ready!");
}

void loop() {
${lines
  .split("\n")
  .map((l) => "  " + l)
  .join("\n")}
}
`;
}

